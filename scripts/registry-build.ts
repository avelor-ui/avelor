import fs from "node:fs"
import path from "node:path"

import { registryOutDir, repoRoot, run, shadcnBin } from "./shared.ts"

fs.rmSync(registryOutDir, { recursive: true, force: true })
await run(process.execPath, [shadcnBin, "build", "-o", registryOutDir], {
  cwd: repoRoot,
})

const catalog = JSON.parse(
  fs.readFileSync(path.join(registryOutDir, "registry.json"), "utf8")
) as { items: { name: string }[] }

const items = Object.fromEntries(
  catalog.items.map((item) => [
    item.name,
    JSON.parse(
      fs.readFileSync(path.join(registryOutDir, `${item.name}.json`), "utf8")
    ),
  ])
)

const generated = `// Generated by scripts/registry-build.ts from registry-out/. Do not edit.

export const registryCatalog = ${JSON.stringify(catalog, null, 2)} as const

export const registryItems = ${JSON.stringify(items, null, 2)} as const

export type RegistryItemName = keyof typeof registryItems
`

const generatedPath = path.join(repoRoot, "lib", "registry", "items.generated.ts")
fs.mkdirSync(path.dirname(generatedPath), { recursive: true })
fs.writeFileSync(generatedPath, generated)
console.log(
  `Wrote ${path.relative(repoRoot, generatedPath)} (${catalog.items.length} item(s))`
)
